def capitalize_gallery_page_title(app, docname, source):
    """Apply the heading style to Sphinx-Gallery's generated timing pages."""
    if docname.rsplit("/", 1)[-1] == "sg_execution_times":
        source[0] = source[0].replace(
            "\nComputation times\n", "\nComputation Times\n", 1
        )


def expand_visualization_contents(
    app, pagename, templatename, context, doctree
):
    """Keep all example setups reachable from the gallery's contents panel."""
    if pagename == "generated/sphinx_gallery_examples/index":
        context["theme_show_toc_level"] = 3
    elif pagename == "generated/sphinx_gallery_examples/1-pool-classification/index":
        context["theme_show_toc_level"] = 2


def setup(app):
    app.connect("source-read", capitalize_gallery_page_title)
    app.connect("html-page-context", expand_visualization_contents)
